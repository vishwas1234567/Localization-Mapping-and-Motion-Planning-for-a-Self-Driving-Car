"""Generate numbers.tex (headline-number macros) and tables/*.tex (one file per table) from results/*.json.

Re-run after any experiment:  python make_tables.py   -> then recompile main.tex.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
R = ROOT / "results"
(ROOT / "tables").mkdir(exist_ok=True)
J = lambda n: json.loads((R / f"{n}.json").read_text())
out = []


def v(x, nd=2, scale=1.0):
    m = x["mean"] if isinstance(x, dict) else (x[0] if isinstance(x, (list, tuple)) else x)
    return f"{m * scale:.{nd}f}"


def pm(x, nd=2, scale=1.0):
    if isinstance(x, dict):
        m, s = x["mean"], x["std"]
    else:
        m, s = x[0], x[1]
    return f"{m * scale:.{nd}f}$\\pm${s * scale:.{nd}f}"


def macro(name, val):
    out.append(f"\\newcommand{{\\{name}}}{{{val}}}")


def table(label, caption, cols, rows, spec=None, note=None):
    spec = spec or "l" + "r" * (len(cols) - 1)
    t = ["% AUTO-GENERATED by make_tables.py", "\\begin{table}[H]\\centering\\small",
         f"\\caption{{{caption}}}\\label{{{label}}}", "\\begin{adjustbox}{max width=\\linewidth}", f"\\begin{{tabular}}{{{spec}}}\\toprule",
         " & ".join(cols) + " \\\\ \\midrule"]
    t += [" & ".join(r) + " \\\\" for r in rows]
    t.append("\\bottomrule\\end{tabular}\\end{adjustbox}")
    if note:
        t.append(f"\\par\\vspace{{2pt}}{{\\footnotesize {note}}}")
    t.append("\\end{table}")
    (ROOT / "tables" / (label.split(":")[1] + ".tex")).write_text("\n".join(t) + "\n")


